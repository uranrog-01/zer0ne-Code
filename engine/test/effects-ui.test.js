'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const { JSDOM } = require('jsdom');

(async () => {
	const dom = new JSDOM('<body><main><canvas id="picture"></canvas></main></body>', { runScripts:'outside-only', pretendToBeVisual:true });
	const win = dom.window, doc = win.document, queue = new Map(), renders = [];
	let serial = 0, focus = true, hidden = false, disposed = 0;
	doc.hasFocus = () => focus;
	Object.defineProperty(doc, 'hidden', { get:() => hidden });
	Object.defineProperty(win, 'devicePixelRatio', { value:2 });
	win.requestAnimationFrame = fn => { queue.set(++serial, fn); return serial; };
	win.cancelAnimationFrame = id => queue.delete(id);
	win.matchMedia = () => ({ matches:false, addEventListener() {} });
	win.ResizeObserver = class { observe() {} disconnect() {} };
	const device = { addEventListener() {}, lost:new Promise(() => {}), createShaderModule:() => ({ getCompilationInfo:async () => ({ messages:[] }) }), destroy() { disposed++; } };
	Object.defineProperty(win.navigator, 'gpu', { value:{ requestAdapter:async () => ({ requestDevice:async () => device }), getPreferredCanvasFormat:() => 'bgra8unorm' } });
	win.HTMLCanvasElement.prototype.getBoundingClientRect = () => ({ width:800, height:600 });
	win.HTMLCanvasElement.prototype.getContext = type => type === 'webgpu' ? { configure() {}, unconfigure() {}, getCurrentTexture:() => ({ createView:() => ({}) }) } : { clearRect() {} };
	win.MetalForgeFilament = { base:{}, shader:'fixture', SimEngine:class { frame(...args) { renders.push(args); } dispose() {} endStroke() {} } };
	win.eval(fs.readFileSync(path.join(__dirname, '../media/effects.js'), 'utf8'));
	win.Effects.mount(doc.getElementById('picture')); win.Effects.set({ filament:true, active:true });
	await new Promise(resolve => setImmediate(resolve));
	const tick = now => { const callbacks = [...queue.values()]; queue.clear(); callbacks.forEach(fn => fn(now)); };
	for (let i = 0; i < 120; i++) tick(i * 1000 / 120);
	assert(renders.length >= 29 && renders.length <= 31, '120 Hz display is capped near 30 GPU frames: ' + renders.length);
	const canvas = doc.getElementById('filament-canvas');
	assert.equal(canvas.width, 1000); assert.equal(canvas.height, 750, 'DPR capped at 1.25');
	const count = renders.length;
	focus = false; win.dispatchEvent(new win.Event('blur')); tick(1100);
	assert.equal(queue.size, 0); assert.equal(renders.length, count);
	focus = true; win.dispatchEvent(new win.Event('focus')); tick(1200);
	assert.equal(renders.length, count + 1);
	hidden = true; doc.dispatchEvent(new win.Event('visibilitychange')); tick(1300); assert.equal(queue.size, 0);
	hidden = false; doc.dispatchEvent(new win.Event('visibilitychange')); tick(1400);
	win.Effects.set({ filament:true, active:false }); tick(1500); assert.equal(queue.size, 0);
	win.eval(fs.readFileSync(path.join(__dirname, '../media/appearance.js'), 'utf8'));
	win.applyAppearance({theme:'terminal'}); tick(1600);
	assert.equal(queue.size,0,'Terminal appearance does not reactivate the GPU loop on an empty chat');
	assert.equal(doc.body.classList.contains('filament-on'),false);
	assert.equal(canvas.hidden,true);
	// Calm (Appearance → Motion) stops decorative loops like the system reduced-motion setting.
	win.applyAppearance({theme:'dark', motion:'full'}); tick(1700);
	assert.ok(queue.size > 0, 'Full motion animates the welcome preview');
	win.applyAppearance({theme:'dark', motion:'calm'}); tick(1800);
	assert.equal(doc.body.dataset.motion, 'calm');
	assert.equal(queue.size, 0, 'Calm stops the decorative GPU loop');
	win.applyAppearance({theme:'dark', motion:'full'}); tick(1900);
	assert.ok(queue.size > 0, 'switching back to Full resumes it');
	win.dispatchEvent(new win.Event('pagehide')); assert.equal(disposed, 1);
	dom.window.close();
	console.log('PASS ambient renderer: 30 fps cap, bounded resolution, focus/visibility pause, cleanup');
})().catch(e => { console.error(e); process.exitCode = 1; });
