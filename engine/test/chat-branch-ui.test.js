'use strict';
const assert = require('node:assert/strict');
const ts = require('typescript-classic');
const { JSDOM } = require('jsdom');
const { readPage } = require('./page-scripts');
const dom = new JSDOM('<body><button id="branch">Branch in new chat</button></body>', { runScripts: 'outside-only' });
const w = dom.window, d = w.document, posts = [];
w.HTMLDialogElement.prototype.showModal = function () { this.open = true; };
w.HTMLDialogElement.prototype.close = function () { this.open = false; this.dispatchEvent(new w.Event('close')); };
const state = { currentSessionId: 'source', hasWorkspace: true, workspace: { path: '/project' } };
w.eval(readPage('chat-branch.js'));
const branch = w.ChatBranch.create({ state: () => state, post: msg => posts.push(JSON.parse(JSON.stringify(msg))), icon: () => '<svg class="i"></svg>' });
const trigger = d.getElementById('branch');
try {
	trigger.focus(); branch.show('answer');
	assert.equal(posts.length, 0, 'opening the chooser must not create a chat');
	assert.equal(d.querySelectorAll('dialog').length, 1);
	assert.equal(d.activeElement.dataset.destination, 'workspace');
	branch.show('answer');
	assert.equal(d.querySelectorAll('dialog').length, 1, 'repeated clicks keep one chooser');
	d.querySelector('[data-destination="workspace"]').click();
	assert.deepEqual(posts.pop(), { type: 'branchChat', id: 'answer', sessionId: 'source', destination: 'workspace' });
	assert.equal(d.querySelector('dialog'), null); assert.equal(d.activeElement, trigger);
	branch.show('answer'); d.querySelector('[data-destination="worktree"]').click();
	assert.deepEqual(posts.pop(), { type: 'branchChat', id: 'answer', sessionId: 'source', destination: 'worktree' });
	branch.show('answer'); d.querySelector('.chat-branch-cancel').click(); assert.equal(posts.length, 0);
	branch.show('answer'); state.currentSessionId = 'another'; d.querySelector('[data-destination="workspace"]').click();
	assert.equal(posts.length, 0, 'a stale dialog cannot fork the new current chat');
	state.workspace = undefined; branch.show('answer');
	assert.ok(d.querySelector('[data-destination="worktree"]').disabled);
	d.querySelector('[data-destination="worktree"]').click(); assert.equal(posts.length, 0);
	d.querySelector('.chat-branch-cancel').click();
	state.isStreaming = true; branch.show('answer'); assert.equal(d.querySelector('dialog'), null);
	state.isStreaming = false; state.isRemote = true; branch.show('answer'); assert.equal(d.querySelector('dialog'), null);
	const source = readPage('chat.js'), ast = ts.createSourceFile('chat.js', source, ts.ScriptTarget.Latest, true, ts.ScriptKind.JS);
	let render;
	function visit(node) { if (ts.isFunctionDeclaration(node) && node.name?.text === 'renderAssistant') render = node.getText(ast); ts.forEachChild(node, visit); }
	visit(ast);
	w.h = (tag, cls, html) => { const node = d.createElement(tag); node.className = cls; node.innerHTML = html || ''; return node; };
	w.state = { settings: {} }; w.ui = {}; w.isNote = () => false; w.MD = { render: text => text };
	w.macButton = (_key, _icon, label) => '<button>' + label + '</button>'; w.t = key => key;
	w.esc = String; w.fmtTime = () => '1:04 PM'; w.usageHtml = () => '<span class="msg-usage">44k in · 14 out</span>';
	w.eval(render);
	const reply = w.renderAssistant({ id: 'a', content: 'Hello', model: 'gpt-6-luna', at: 1 }, { final: true, last: true, turn: { provider: 'ChatGPT · account@example.com' } });
	assert.equal(reply.querySelector('.msg-model'), null);
	assert.match(reply.textContent, /Hello.*copy.*retry.*branchChat.*1:04 PM.*44k in · 14 out/);
	assert.ok(!reply.innerHTML.includes('account@example.com') && !reply.innerHTML.includes('gpt-6-luna'));
	console.log('PASS branch destination chooser, cancellation, focus, stale chat guards and compact response footer');
} finally { dom.window.close(); }
