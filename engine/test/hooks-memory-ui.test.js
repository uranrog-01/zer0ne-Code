'use strict';
const assert = require('node:assert/strict'), fs = require('node:fs'), path = require('node:path');
const { JSDOM } = require('jsdom');
const dom = new JSDOM('<body><div id="settings-root"></div><div id="dialog-root"></div><div id="toast"></div></body>', {runScripts:'outside-only',pretendToBeVisual:true});
const w = dom.window, posts = [], saved = {settingsSection:'hooks',hooksMemoryTab:'hooks'}, errors = [];
w.Bridge = {desktop:true,remote:false,getState:()=>saved,patchState:patch=>Object.assign(saved,patch),post:message=>posts.push(message)};
w.Icons = {svg:()=>'<svg></svg>'};
w.matchMedia = () => ({matches:true,addEventListener(){},removeEventListener(){}});
w.HTMLElement.prototype.scrollIntoView = function() {};
w.addEventListener('error', e => errors.push(e.message));
const media = path.resolve(__dirname,'../media');
for (const file of ['settings-remote.js','settings-search.js','settings-index.js']) w.eval(fs.readFileSync(path.join(media,file),'utf8'));
w.eval(require('./page-scripts').readPage('settings.js'));
const send = patch => w.dispatchEvent(new w.MessageEvent('message',{data:{type:'state',version:'fixture',settings:{uiMode:'simple'},providers:[],presets:[],memories:[],hooks:[],...patch}}));
try {
	send({}); w.Settings.open();
	const d = w.document, click = selector => d.querySelector(selector).click();
	assert.equal(d.querySelector('.page-title').textContent,'Hooks & Memory');
	assert.equal(d.querySelectorAll('[data-nav="hooks-memory"]').length,1);
	assert(!d.querySelector('[data-nav="hooks"], [data-nav="memory"]'));
	assert(d.querySelector('[data-act="hook-add"]'), 'old Hooks section restores on the Hooks tab');
	click('[data-act="hook-add"]');
	assert(d.getElementById('hk-command'),'hook editor remains available');
	d.querySelector('[data-cancel]').click();
	d.getElementById('hooks-memory-tab-hooks').dispatchEvent(new w.KeyboardEvent('keydown',{key:'ArrowRight',bubbles:true,cancelable:true}));
	assert.equal(d.activeElement.id,'hooks-memory-tab-memory');
	assert.equal(d.getElementById('hooks-memory-panel').getAttribute('aria-labelledby'),'hooks-memory-tab-memory');
	d.getElementById('mem-add').value='Keep this unsaved draft';
	click('#hooks-memory-tab-hooks'); click('#hooks-memory-tab-memory');
	assert.equal(d.getElementById('mem-add').value,'Keep this unsaved draft');
	send({memories:[{id:'one',text:'Fixture memory',ts:1}]});
	assert.equal(d.querySelector('[aria-selected="true"][data-hooks-memory-tab]').dataset.hooksMemoryTab,'memory','state refresh keeps the selected tab');
	assert.equal(d.getElementById('mem-add').value,'Keep this unsaved draft','state refresh keeps the draft');
	click('[data-act="memory-add"]');
	assert(posts.some(m=>m.type==='saveMemory'&&m.text==='Keep this unsaved draft'),'memory creation is still wired to its existing command');
	click('#hooks-memory-tab-hooks'); click('#hooks-memory-tab-memory');
	assert.equal(d.getElementById('mem-add').value,'','a saved draft is not restored');
	w.Settings.open('hooks'); assert(d.querySelector('[data-act="hook-add"]'));
	w.Settings.open('memory'); assert(d.getElementById('mem-add'));
	w.Settings.close(); w.Settings.open();
	assert(d.getElementById('mem-add'),'reopening keeps the last selected tab');
	send({settings:{uiMode:'pro'}});
	assert.equal(d.querySelectorAll('[data-nav="hooks-memory"]').length,1,'Pro view also has one merged entry');
	assert(!d.querySelector('[data-nav="hooks"], [data-nav="memory"]'));
	const search = d.querySelector('.settings-search input');
	search.value='Include sensitive topics'; search.dispatchEvent(new w.Event('input'));
	search.dispatchEvent(new w.KeyboardEvent('keydown',{key:'Enter',bubbles:true,cancelable:true}));
	assert.equal(d.activeElement.dataset.setting,'memorySensitive','search selects and focuses the Memory control');
	search.value='Hooks'; search.dispatchEvent(new w.Event('input'));
	search.dispatchEvent(new w.KeyboardEvent('keydown',{key:'Enter',bubbles:true,cancelable:true}));
	assert(d.querySelector('[data-act="hook-add"]'),'Hooks search opens its tab');
	assert.equal(saved.settingsSection,'hooks-memory');
	assert.equal(saved.hooksMemoryTab,'hooks');
	assert.deepEqual(errors,[]);
	console.log('Hooks & Memory passed: one Simple/Pro route, legacy links, keyboard tabs, draft retention, memory save and search targets.');
} finally { w.close(); }
