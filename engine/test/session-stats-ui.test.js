'use strict';
const assert = require('node:assert/strict');


const ts = require('typescript-classic');
const { JSDOM } = require('jsdom');
const { CHAT_BODY } = require('../out/webviewMarkup');

const source = require('./page-scripts').readPage('chat.js').replace(/\r\n/g, '\n');
const ast = ts.createSourceFile('chat.js', source, ts.ScriptTarget.Latest, true, ts.ScriptKind.JS);
const names = new Set(['h', 'tickerHtml', 'rollTickers', 'sessionStats', 'statsDuration', 'renderStats', 'fmtDuration', 'fmtTokens', 'fmtK', 'fmtCacheRate', 'ctxRingSvg', 'positionStatsPopup', 'renderStatsPopup', 'closeStatsPopup', 'toggleStatsPopup']);
const code = [];
function visit(node) {
	if (ts.isFunctionDeclaration(node) && names.has(node.name?.text)) code.push(node.getText(ast));
	if (ts.isVariableDeclaration(node) && node.name.getText(ast).startsWith('fmt') && names.has(node.name.getText(ast))) code.push('const ' + node.getText(ast) + ';');
	if (ts.isExpressionStatement(node) && (/^\$\('(btn-stats|stats-content|stats-banner)'\)\?\.addEventListener/.test(node.getText(ast)) || node.getText(ast).startsWith("document.addEventListener('pointerdown', e => {\n\t\tif (ui.statsPopup") || node.getText(ast).startsWith("window.addEventListener('resize', positionStatsPopup") || node.getText(ast).startsWith("document.addEventListener('scroll', positionStatsPopup"))) code.push(node.getText(ast));
	ts.forEachChild(node, visit);
}
visit(ast);
assert.equal(code.length, names.size + 6);
const dom = new JSDOM('<body>' + CHAT_BODY + '</body>', { runScripts: 'outside-only', pretendToBeVisual: true });
const w = dom.window;
w.$ = id => w.document.getElementById(id);
w.state = { messages: [], context: null, currentSessionId: 'a' };
w.closeMenus = () => {};
w.ui = { statsOpen: false, statsPopup: null };
w.esc = value => String(value).replace(/[&<>"']/g, c => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' })[c]);
w.I = () => '<svg class="i" aria-hidden="true"></svg>';
const saved = { draft: 'Keep my draft' };
w.B = { patchState: patch => Object.assign(saved, patch) };
w.eval(code.join('\n'));

const attempt = (step, extra = {}) => ({ step, purpose: 'main', durationMs: 3000, firstTextMs: 1000, outcome: 'completed', usage: { input: 1000, output: 100, cached: 800 }, ...extra });
const turn = (attempts, extra = {}) => ({ role: 'user', turn: { startedAt: 1, attempts, ...extra } });

(async () => {
	const stats = w.sessionStats([turn([attempt(0), attempt(0, { outcome: 'failed', usage: undefined, firstTextMs: undefined }), attempt(1, { firstReasoningMs: 500 })], { toolTimings: [{ durationMs: 1250 }, { durationMs: 750 }] })]);
	assert.equal(stats.turns, 1);
	assert.equal(stats.steps, 2, 'retry does not add a step');
	assert.equal(stats.requests, 3);
	assert.equal(stats.llmMs, 9000);
	assert.equal(stats.toolMs, 2000);
	assert.equal(stats.ttftMs / stats.ttftSamples, 750, 'first reasoning token counts before text');
	assert.equal(stats.decodeMs, 4500);
	assert.equal(stats.tps, 200 / 4.5);
	assert.equal(stats.partial, true);
	assert.equal(stats.cacheRate, null, 'partial reports cannot imply a complete cache hit rate');
	const complete = w.sessionStats([turn([attempt(0), attempt(1)])]);
	assert.equal(complete.cacheRate, 80);
	const zero = w.sessionStats([turn([attempt(0, { firstTextMs: 0, usage: { input: 0, output: 0, cached: 0 } })])]);
	assert.equal(zero.known, 1);
	assert.equal(zero.tps, 0, 'measured zero differs from missing speed');
	assert.equal(zero.cacheRate, null, 'empty input has no cache ratio');
	const legacy = w.sessionStats([turn([], { usage: { input: 1200, output: 90 } })]);
	assert.equal(legacy.requestCountsKnown, false);
	assert.equal(legacy.cacheRate, null);
	assert.equal(legacy.llmSamples, 0);
	assert.equal(w.sessionStats([turn([attempt(0, { usage: { input: 100, output: 0, inputReported: true, outputReported: false } })])]).partial, true);
	assert.equal(w.sessionStats([turn([attempt(0, { purpose: 'child' })])]).steps, 0);
	assert.equal(w.sessionStats([turn([attempt(0, { firstTextMs: 4000 })])]).ttftSamples, 0);

	const banner = w.$('stats-banner'), button = w.$('btn-stats');
	w.renderStats();
	assert.equal(banner.inert, true);
	assert.equal(button.getAttribute('aria-expanded'), 'false');
	w.state.messages = [turn([attempt(0)])];
	w.state.context = { used: 197000, window: 262000, source: 'estimated', parts: { messages: 90, systemPrompt: 10 } };
	button.click();
	assert.equal(banner.inert, false);
	assert.equal(button.getAttribute('aria-expanded'), 'true');
	assert.equal(saved.statsOpen, true);
	assert.equal(saved.draft, 'Keep my draft');
	assert.equal(banner.querySelectorAll('[data-stats-kind]').length, 3);
	assert.equal(banner.querySelector('details'), null, 'metrics never expand the row');
	assert.match(banner.textContent, /1 turn 1 step · 50 tok\/s/);
	assert.match(banner.textContent, /1\.1k tok · Cache hit 80%/);
	assert.match(banner.textContent, /75%/);
	assert.equal(w.$('stats-popup'), null, 'revealing Stats only shows the metric row');
	const tokenTrigger = w.$('stats-tokens');
	tokenTrigger.click();
	let popup = w.$('stats-popup');
	assert.equal(popup.getAttribute('role'), 'dialog');
	assert.match(popup.textContent, /Token usage/);
	assert.match(popup.textContent, /Cached input800 tok/);
	assert.equal(tokenTrigger.getAttribute('aria-expanded'), 'true');
	assert.equal(w.document.activeElement, popup);
	tokenTrigger.getBoundingClientRect = () => ({ left: 600, top: 700, width: 180, height: 24 });
	Object.defineProperties(popup, { offsetWidth: { get: () => 360 }, offsetHeight: { get: () => 250 } });
	popup.getBoundingClientRect = () => ({ width: 352.8, height: 245 });
	w.positionStatsPopup();
	assert.equal(parseFloat(popup.style.top) + popup.offsetHeight, 692, 'opening animation cannot reduce the gap above the trigger');
	assert.equal(parseFloat(popup.style.left), 510, 'centering uses the final popup width');
	const originalPopup = popup;
	w.state.messages.push(turn([attempt(0)]));
	w.renderStats();
	assert.equal(w.$('stats-popup'), originalPopup, 'live updates preserve the open popup');
	assert.equal(w.document.activeElement, popup, 'live updates preserve focus');
	assert.match(popup.textContent, /Cached input1,600 tok/);
	w.$('stats-context').click();
	popup = w.$('stats-popup');
	assert.equal(w.document.querySelectorAll('#stats-popup').length, 1);
	assert.equal(tokenTrigger.getAttribute('aria-expanded'), 'false');
	assert.match(popup.textContent, /~197K/);
	assert.equal(popup.querySelector('[role="progressbar"]').getAttribute('aria-valuenow'), '75.2');
	popup.dispatchEvent(new w.KeyboardEvent('keydown', { key: 'Escape', bubbles: true }));
	assert.equal(w.$('stats-popup'), null);
	assert.equal(w.document.activeElement, w.$('stats-context'));
	assert.equal(button.getAttribute('aria-expanded'), 'true', 'Escape closes the popup before the Stats row');
	w.$('stats-session').click();
	assert.match(w.$('stats-popup').textContent, /Avg\. time to first token/);
	w.$('stats-session').click();
	assert.equal(w.$('stats-popup'), null, 'clicking the same metric toggles its popup');
	w.$('stats-session').click();
	w.document.body.dispatchEvent(new w.Event('pointerdown', { bubbles: true }));
	assert.equal(w.$('stats-popup'), null, 'outside clicks dismiss');
	w.$('stats-tokens').click();
	w.$('stats-popup').querySelector('.stats-popup-close').click();
	assert.equal(w.$('stats-popup'), null);
	assert.equal(w.document.activeElement, tokenTrigger, 'close button restores metric focus');
	w.$('stats-tokens').click();
	button.click();
	assert.equal(w.$('stats-popup'), null, 'hiding Stats also closes its popup');
	assert.equal(banner.inert, true);
	assert.equal(saved.statsOpen, false);
	button.click();
	w.$('stats-tokens').click();
	w.state.currentSessionId = 'b';
	w.state.messages = [];
	w.state.context = null;
	w.renderStats();
	assert.equal(w.$('stats-popup'), null, 'changing chats dismisses the old popup');
	assert.match(banner.textContent, /0 turns/);
	assert.doesNotMatch(banner.textContent, /197K|80%/, 'empty chats clear previous metrics');
	w.$('stats-context').click();
	assert.match(w.$('stats-popup').textContent, /Send a message to measure/);
	w.state.context = { used: 150, window: 100, parts: {} };
	w.renderStats();
	assert.equal(w.$('stats-popup').querySelector('[role="progressbar"]').getAttribute('aria-valuenow'), '100.0');
	assert.match(banner.textContent, /150%/, 'over-capacity text stays honest');
	w.$('stats-popup').dispatchEvent(new w.KeyboardEvent('keydown', { key: 'Escape', bubbles: true }));
	banner.dispatchEvent(new w.KeyboardEvent('keydown', { key: 'Escape', bubbles: true }));
	assert.equal(banner.inert, true);
	assert.equal(w.document.activeElement, button);
	console.log('Session stats UI passed: retries, measured timing, partial/cache coverage, live counts, compact metrics, popups, focus, outside dismissal and session changes.');
})().catch(error => { console.error(error); process.exitCode = 1; }).finally(() => dom.window.close());
