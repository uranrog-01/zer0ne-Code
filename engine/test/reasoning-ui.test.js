// Exercise the production reasoning banner with real DOM range events.
const assert = require('node:assert/strict');
const vm = require('node:vm'), ts = require('typescript-classic');
const { JSDOM } = require('jsdom');
const source = require('./page-scripts').readPage('chat.js');
const ast = ts.createSourceFile('chat.js', source, ts.ScriptTarget.Latest, true, ts.ScriptKind.JS);
const names = new Set(['effortLabel', 'effortLevels', 'renderEffortMenu']);
const declarations = [];
const visit = node => {
 if (ts.isFunctionDeclaration(node) && names.has(node.name?.text)) declarations.push(node.getText(ast));
 if (ts.isVariableStatement(node) && node.declarationList.declarations.some(d => d.name.getText(ast) === 'ALL_LEVELS')) declarations.push(node.getText(ast));
 ts.forEachChild(node, visit);
};
visit(ast); assert.equal(declarations.length, 4);
const dom = new JSDOM('<body><button id="effort">Auto</button><div id="menu"></div></body>');
const menu = dom.window.document.getElementById('menu'), effort = dom.window.document.getElementById('effort'), posts = [];
let selectedModel, closed = 0;
const context = vm.createContext({ el: { effortMenu: menu, effort }, selected: () => selectedModel, t: key => key, I: () => '', esc: value => String(value).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/"/g, '&quot;'), post: message => posts.push(message), closeMenus: () => closed++ });
vm.runInContext(declarations.join('\n'), context);
selectedModel = { provider: { id: 'p', efforts: { unknown: 'high' }, reasoningControls: { unknown: { levels: [], note: 'No supported server control; Auto uses its default.' } } }, model: { id: 'unknown' } };
context.renderEffortMenu();
assert.equal(menu.querySelector('.ef-slider'), null, 'unsupported models have no invented scale');
assert.equal(menu.querySelector('.ef-value').textContent, 'Auto');
assert.equal(posts.length, 0);
const supported = ['none', 'minimal', 'low', 'medium', 'high', 'xhigh', 'maximum'];
selectedModel = { provider: { id: 'p', efforts: {}, reasoningControls: { all: { levels: supported, note: 'Documented levels <script>' } } }, model: { id: 'all' } };
context.renderEffortMenu();
assert.equal(menu.querySelectorAll('button, .ef-options, .ef-note, .ef-model, .ef-captions').length, 0, 'the menu contains only the heading and slider banner');
assert(!menu.textContent.includes('Documented levels')); assert.equal(menu.querySelector('script'), null);
const slider = menu.querySelector('.ef-slider');
assert.equal(slider.max, '7'); assert.equal(slider.getAttribute('aria-valuetext'), 'Auto');
slider.value = '7'; slider.dispatchEvent(new dom.window.Event('input'));
assert.equal(menu.querySelector('.ef-value').textContent, 'Maximum');
assert.equal(slider.getAttribute('aria-valuetext'), 'Maximum');
assert.equal(posts.length, 0, 'dragging previews without sending provider changes');
slider.dispatchEvent(new dom.window.Event('change'));
assert.equal(posts.pop().effort, 'maximum');
assert.equal(closed, 1); assert.equal(dom.window.document.activeElement, effort);
slider.value = '0'; slider.dispatchEvent(new dom.window.Event('input')); slider.dispatchEvent(new dom.window.Event('change'));
assert.equal(posts.length, 0, 'selecting the saved Auto value makes no provider change');
selectedModel = { provider: { id: 'agent', efforts: { 'gemini-high': 'low' }, reasoningControls: { 'gemini-high': { levels: ['low', 'high'], note: 'Advertised variants', choices: [{ effort: 'low', value: 'gemini-low', name: 'Gemini (Low)', model: true }] } } }, model: { id: 'gemini-high', name: 'Gemini (High)' } };
context.renderEffortMenu();
const variantSlider = menu.querySelector('.ef-slider');
assert.equal(variantSlider.max, '2'); assert.equal(variantSlider.value, '1');
variantSlider.value = '2'; variantSlider.dispatchEvent(new dom.window.Event('input')); variantSlider.dispatchEvent(new dom.window.Event('change'));
assert.deepEqual(JSON.parse(JSON.stringify(posts.pop())), { type:'setEffort', providerId:'agent', model:'gemini-high', effort:'high' });
context.renderEffortMenu();
const reset = menu.querySelector('.ef-slider'); reset.value = '0'; reset.dispatchEvent(new dom.window.Event('change'));
assert.equal(posts.pop().effort, 'max', 'Auto remains selectable through the banner');
selectedModel = { provider: { id: 'missing', efforts: {} }, model: { id: 'new-model' } }; context.renderEffortMenu();
assert.equal(menu.querySelector('.ef-slider'), null, 'no invented reasoning scale for unsupported models');
console.log('PASS reasoning UI: banner only, supported levels, preview, commit, Auto, focus return and agent variants');
