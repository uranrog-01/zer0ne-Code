'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const { JSDOM } = require('jsdom');
const source = file => fs.readFileSync(path.join(__dirname, '..', file), 'utf8');

async function run() {
	const dom = new JSDOM('<body class="desktop"><header class="topbar"><button id="btn-fullscreen"></button><button id="menu-button" aria-haspopup="menu" aria-expanded="false"></button></header><aside id="sidebar"></aside><div id="messages"></div><textarea id="input"></textarea><div id="lightbox" class="hidden"></div><div id="settings-root"></div></body>', { runScripts: 'outside-only', pretendToBeVisual: true });
	const window = dom.window, document = window.document;
	const posts = [], timers = [];
	let nativeFullscreen = false;
	const hideTimers = new Map();
	let timerId = 0;
	window.setTimeout = callback => { hideTimers.set(++timerId, callback); return timerId; };
	window.clearTimeout = id => hideTimers.delete(id);
	const tick = () => { for (const [id, callback] of [...hideTimers]) { hideTimers.delete(id); callback(); } };
	const bar = document.querySelector('.topbar');
	bar.getBoundingClientRect = () => ({ left:12, right:988, bottom:60 });
	window.post = message => posts.push(JSON.parse(JSON.stringify(message)));
	window.win = async command => { assert.equal(command, 'is_fullscreen'); return nativeFullscreen; };
	window.Icons = { svg: icon => '<svg data-icon="' + icon + '"></svg>' };
	const desktop = source('app/desktop-ui.js');
	const begin = desktop.indexOf('\tfunction fullscreen()');
	const end = desktop.indexOf('\n\t/**', begin);
	window.eval(desktop.slice(begin, end) + '\nfullscreen();');
	await Promise.resolve();
	const chat = source('engine/media/chat.js');
	const toggleBegin = chat.indexOf('\tfunction fsToggle(on)');
	const toggleEnd = chat.indexOf('\n\tfunction reducedMotion()', toggleBegin);
	window.B = { desktop: true };
	window.$ = id => document.getElementById(id);
	window.FS = false;
	window.reducedMotion = () => false;
	window.eval(chat.slice(toggleBegin, toggleEnd) + '\nwindow.__fsExit = () => fsToggle(false);');
	const controlsBegin = chat.indexOf("\tif ($('btn-fullscreen'))");
	const controlsEnd = chat.indexOf('\n\tif (FS) {', controlsBegin);
	window.eval(chat.slice(controlsBegin, controlsEnd));
	const escapeGuard = chat.indexOf("if (e.defaultPrevented || e.isComposing || e.keyCode === 229 || e.key !== 'Escape'");
	const escapeBegin = chat.lastIndexOf("\tdocument.addEventListener('keydown'", escapeGuard);
	const escapeEnd = chat.indexOf('\n\tconst imageViewer', escapeGuard);
	window.questionUi = {}; window.ui = {}; window.state = { isStreaming: true };
	window.el = { lightbox: document.getElementById('lightbox') };
	window.eval(chat.slice(escapeBegin, escapeEnd));
	const button = document.getElementById('btn-fullscreen');
	const composer = document.getElementById('input'); composer.value = 'Unsent work'; composer.focus();
	const messages = document.getElementById('messages'); messages.scrollTop = 280;
	const sidebar = document.getElementById('sidebar');
	button.click(); assert.deepEqual(posts.pop(), { type: 'fullscreen', on: true });
	window.__zcSetFullscreen(true); nativeFullscreen = true;
	assert.equal(button.getAttribute('aria-pressed'), 'true');
	assert.equal(button.getAttribute('aria-label'), 'Exit full screen');
	assert(!document.body.classList.contains('fullscreen'));
	assert.equal(document.getElementById('messages'), messages);
	assert.equal(document.getElementById('sidebar'), sidebar);
	assert.equal(messages.scrollTop, 280);
	assert.equal(composer.value, 'Unsent work'); assert.equal(document.activeElement, composer);
	const peek = document.querySelector('.zc-fullscreen-peek');
	assert.equal(bar.inert, true, 'hidden window controls cannot take keyboard focus');
	assert.equal(peek.hidden, false);
	assert.equal(peek.getAttribute('aria-controls'), bar.id);
	const pointer = y => document.dispatchEvent(new window.MouseEvent('pointermove', { clientX:500, clientY:y, bubbles:true }));
	const shown = () => document.body.classList.contains('zc-fullscreen-bar-visible');
	pointer(5); assert(shown()); assert.equal(bar.inert, false);
	pointer(66); tick(); assert(shown(), 'the gap between the top edge and floating bar stays reachable');
	pointer(200); assert(shown(), 'moving away allows time to finish using a control'); tick(); assert(!shown());
	pointer(5); document.getElementById('menu-button').setAttribute('aria-expanded', 'true');
	pointer(200); tick(); assert(shown(), 'open toolbar menus hold their anchor in place');
	document.getElementById('menu-button').setAttribute('aria-expanded', 'false'); tick(); assert(!shown());
	document.dispatchEvent(new window.KeyboardEvent('keydown', { key:'F6', bubbles:true, cancelable:true }));
	assert(shown()); assert.equal(document.activeElement, button, 'F6 reaches the hidden controls');
	pointer(200); tick(); assert(shown(), 'keyboard focus keeps controls visible');
	composer.focus(); tick(); assert(!shown());
	assert.equal(messages.scrollTop, 280, 'revealing and hiding never scroll the chat');
	pointer(5); window.dispatchEvent(new window.Event('blur')); assert(!shown(), 'an inactive window resets the floating bar');
	button.click(); assert.deepEqual(posts.pop(), { type: 'fullscreen', on: false });
	const key = options => document.dispatchEvent(new window.KeyboardEvent('keydown', { bubbles: true, cancelable: true, ...options }));
	key({ key: 'Escape' }); assert.deepEqual(posts.pop(), { type: 'fullscreen', on: false });
	assert.equal(timers.length, 0, 'desktop exits without the old fold timer');
	key({ key: 'F11' }); assert.deepEqual(posts.pop(), { type: 'fullscreen', on: false });
	key({ key: 'f', ctrlKey: true, altKey: true }); assert.deepEqual(posts.pop(), { type: 'fullscreen', on: false });
	window.__zcSetFullscreen(false); nativeFullscreen = false;
	assert.equal(bar.inert, false); assert.equal(peek.hidden, true); assert(!shown());
	key({ key: 'F11' }); assert.deepEqual(posts.pop(), { type: 'fullscreen', on: true });
	key({ key: 'f', ctrlKey: true, altKey: true }); assert.deepEqual(posts.pop(), { type: 'fullscreen', on: true });
	assert.equal(posts.length, 0, 'keys issue one request and never stop the run');
	nativeFullscreen = true;
	window.dispatchEvent(new window.MessageEvent('message', { data: { type: 'zcDesktopActivated' } }));
	await Promise.resolve();
	assert(document.body.classList.contains('zc-native-fullscreen'), 'a retained project catches up with the shared window');
	document.getElementById('settings-root').innerHTML = '<div class="settings-overlay"></div>';
	key({ key: 'Escape' }); assert.equal(posts.length, 0, 'settings handles its own Escape before fullscreen');
	window.B.desktop = false; window.FS = true;
	window.setTimeout = callback => timers.push(callback);
	document.body.classList.add('fullscreen');
	window.fsToggle(false);
	assert.equal(timers.length, 1, 'the extension fullscreen transition retains its existing behavior');
	assert(document.body.classList.contains('fs-folding'));
	timers[0](); assert.deepEqual(posts.pop(), { type: 'fullscreen', on: false });
	const ops = source('app/ops.js');
	const fullscreenOp = ops.slice(ops.indexOf("case 'fullscreen': {"), ops.indexOf("case 'openApplet':"));
	assert(!fullscreenOp.includes('reload'), 'native toggle preserves the page');
	assert(source('app/engines.js').includes('window.__zcSetFullscreen && window.__zcSetFullscreen('), 'the page learns the native state');
	assert(require('../app/permissions').allowed('engine', 'plugin:window|is_fullscreen'));
	const { EngineWindow } = require('../app/engines');
	const restored = [];
	EngineWindow.prototype.toggleMaximize.call({ isFullscreen:() => true, setFullscreen:on => restored.push(on) });
	assert.deepEqual(restored, [false], 'the restore control exits full screen through the native window');
	if (process.platform === 'win32') {
		const host = Object.create(EngineWindow.prototype), requests = [];
		host.shell = { state: {}, syncIcons() {} };
		host.transparent = true; host.fullscreen = false; host.fsMaximized = false;
		let maximized = true;
		host.win = { isFullScreen:() => false, isMaximized:() => maximized, setFullScreen:on => requests.push(on), unmaximize:() => { maximized = false; }, maximize:() => { maximized = true; } };
		host.evalActive = () => {};
		let saves = 0; host.rememberSize = () => saves++;
		host.setFullscreen(true); assert.equal(host.isFullscreen(), true);
		host.setFullscreen(true); assert.deepEqual(requests, [true], 'repeated entry cannot overwrite the restore bounds');
		host.setFullscreen(false); host.setFullscreen(false);
		assert.equal(host.isFullscreen(), false); assert.equal(maximized, true);
		assert.deepEqual(requests, [true, false]); assert.equal(saves, 1);
		const handle = require('../app/ops').handle;
		assert.equal(await handle(host.ctx(), { op:'fullscreen' }), true);
		assert.equal(await handle(host.ctx(), { op:'fullscreen' }), false);
		assert.deepEqual(requests, [true, false, true, false], 'engine toggle requests use the owning window state');
	}
	window.win = async command => posts.push(command);
	const dragBegin = desktop.indexOf('\tfunction draggable(bar)');
	const dragEnd = desktop.indexOf('\n\tfunction frame()', dragBegin);
	window.eval(desktop.slice(dragBegin, dragEnd) + '\ndraggable(document.querySelector(".topbar"));');
	const doubleClick = (target, button = 0) => target.dispatchEvent(new window.MouseEvent('dblclick', { bubbles:true, button }));
	doubleClick(bar); assert.equal(posts.pop(), 'toggle_maximize', 'renderer title-bar double-click reaches the owning window');
	const countBefore = posts.length;
	doubleClick(button); doubleClick(bar, 2);
	assert.equal(posts.length, countBefore, 'controls and non-primary clicks cannot toggle the window');
	dom.window.close();
	console.log('Fullscreen passed: native toggle, floating controls, pointer/focus/menu lifecycle, unchanged chat/draft/scroll, restore/F6/F11/Ctrl+Alt+F/Esc, activation and overlays.');
}
run().catch(error => { console.error(error); process.exitCode = 1; });
