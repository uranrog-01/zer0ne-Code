'use strict';
require('./project-panel');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const { JSDOM } = require('jsdom');
const { desktopProjects } = require('../host/host');

(async () => {
	const dom = new JSDOM('<body><button id="launch">Delete</button></body>', { runScripts: 'outside-only' });
	const win = dom.window, doc = win.document, sent = [];
	win.HTMLDialogElement.prototype.showModal = function () { this.setAttribute('open', ''); };
	win.HTMLDialogElement.prototype.close = function () { this.removeAttribute('open'); this.dispatchEvent(new win.Event('close')); };
	win.eval(fs.readFileSync(path.join(__dirname, '../engine/media/chat-project-actions.js'), 'utf8'));
	let filesOpened = 0;
	const actions = win.ChatProjectActions.create({ session: id => id === 'saved' ? { title: '<img src=x> Task' } : null, post: m => sent.push(JSON.parse(JSON.stringify(m))), files: () => filesOpened++,
		menu: (_anchor, entries) => { doc.querySelectorAll('.row-menu').forEach(menu => menu.remove()); const menu = doc.createElement('div'); menu.className = 'row-menu'; menu.append(...entries); doc.body.appendChild(menu); return menu; },
		item: (_icon, label, opts) => { const button = doc.createElement('button'); button.className = opts.cls; button.textContent = label; button.disabled = !!opts.disabled; button.onclick = opts.onClick; return button; }, navigate() {}
	});
	doc.getElementById('launch').focus(); actions.deleteChat('saved');
	assert.equal(doc.activeElement.textContent, 'No');
	assert.equal(doc.querySelector('dialog img'), null);
	doc.querySelector('.project-action-no').click();
	assert.equal(sent.length, 0); assert.equal(doc.activeElement.id, 'launch');
	actions.deleteChat('saved');
	const escaped = doc.querySelector('dialog');
	escaped.dispatchEvent(new win.Event('cancel', { cancelable: true })); escaped.close();
	assert.equal(sent.length, 0, 'Escape never deletes a chat');
	actions.deleteChat('saved'); actions.deleteChat('saved');
	assert.equal(doc.querySelectorAll('dialog').length, 1);
	doc.querySelector('form').dispatchEvent(new win.Event('submit', { cancelable: true }));
	assert.deepEqual(sent, [{ type: 'deleteSession', id: 'saved' }]);
	actions.renameProject('C:/alpha', 'Alpha');
	doc.querySelector('input').value = '  New label  ';
	doc.querySelector('form').dispatchEvent(new win.Event('submit', { cancelable: true }));
	assert.deepEqual(sent.at(-1), { type: 'projectRename', path: 'C:/alpha', name: 'New label' });
	actions.showFiles('C:/alpha');
	assert.deepEqual(sent.at(-1), { type: 'projectShowFiles', path: 'C:/alpha' });
	const activation = { type: 'zcDesktopActivated', activationId: 'files-1', view: 'files' };
	win.dispatchEvent(new win.MessageEvent('message', { data: activation, source: {} }));
	assert.equal(filesOpened, 0, 'embedded documents cannot open Work Details');
	win.dispatchEvent(new win.MessageEvent('message', { data: activation }));
	win.dispatchEvent(new win.MessageEvent('message', { data: activation }));
	assert.equal(filesOpened, 1, 'a repeated ready acknowledgment does not reopen a closed panel');
	win.dispatchEvent(new win.MessageEvent('message', { data: { ...activation, activationId: 'files-2' } }));
	assert.equal(filesOpened, 2, 'a later Show Files click opens the panel again');
	const anchor = doc.getElementById('launch'), project = { path: 'C:/alpha', name: 'Alpha', current: false, available: false };
	actions.projectMenu(project, anchor);
	assert.equal(anchor.getAttribute('aria-expanded'), 'true');
	assert(doc.querySelector('.project-show-files').disabled);
	assert.equal(doc.activeElement, doc.querySelector('.project-rename'), 'focus skips unavailable actions');
	assert.equal(doc.querySelectorAll('[role="menuitem"]').length, 4);
	actions.projectMenu(project, anchor);
	assert.equal(doc.querySelector('.project-folder-menu'), null); assert.equal(anchor.getAttribute('aria-expanded'), 'false');
	actions.projectMenu({ ...project, available: true }, anchor); doc.querySelector('.project-show-files').click();
	assert.deepEqual(sent.at(-1), { type: 'projectShowFiles', path: project.path }); assert.equal(doc.activeElement, anchor);
	actions.projectMenu(project, anchor); doc.querySelector('.project-pin').click();
	assert.deepEqual(sent.at(-1), { type: 'projectPin', path: project.path, pinned: true });
	actions.projectMenu({ ...project, pinned: true, current: true }, anchor);
	assert.equal(doc.querySelector('.project-pin').textContent, 'Unpin project'); assert.equal(doc.querySelector('.project-remove'), null);
	doc.querySelector('.project-pin').click();
	assert.deepEqual(sent.at(-1), { type: 'projectPin', path: project.path, pinned: false });
	const count = sent.length;
	actions.projectMenu(project, anchor); doc.querySelector('.project-remove').click(); doc.querySelector('.project-action-no').click();
	assert.equal(sent.length, count, 'No keeps the project in the list');
	actions.projectMenu(project, anchor); doc.querySelector('.project-remove').click(); doc.querySelector('form').dispatchEvent(new win.Event('submit', { cancelable: true }));
	assert.deepEqual(sent.at(-1), { type: 'projectRemove', path: project.path });
	dom.window.close();

	const alpha = path.resolve('alpha'), beta = path.resolve('beta'), key = p => p.toLowerCase();
	const values = { 'aiChat.projects': [alpha, beta] };
	const state = { get: (k, fallback) => values[k] ?? fallback, update: async (k, value) => { values[k] = value; } };
	const message = { type: 'projects', projects: [alpha, beta].map(folder => ({ id: key(folder), path: folder, name: path.basename(folder), chats: [{ id: folder }] })) };
	const projects = desktopProjects({ globalState: state }, key);
	projects.filter(message);
	await assert.rejects(projects.handle({ type: 'projectPin', path: path.resolve('unknown'), pinned: true }, async () => {}), /project list/);
	await assert.rejects(projects.handle({ type: 'projectRename', path: alpha, name: '  ' }, async () => {}), /project name/);
	await assert.rejects(projects.handle({ type: 'projectPin', path: alpha, pinned: 'true' }, async () => {}), /whether to pin/);
	await projects.handle({ type: 'projectRename', path: beta, name: 'Favorite project' }, async () => {});
	await projects.handle({ type: 'projectPin', path: beta, pinned: true }, async () => {});
	const restarted = desktopProjects({ globalState: state }, key);
	const pinned = restarted.filter(message).projects;
	assert.equal(pinned[0].path, beta); assert.equal(pinned[0].name, 'Favorite project'); assert.equal(pinned[0].pinned, true);
	assert.deepEqual(pinned[0].chats, message.projects[1].chats);
	assert.deepEqual(values['aiChat.projects'], [alpha, beta], 'pinning preserves the unpinned order');
	await restarted.handle({ type: 'projectPin', path: beta, pinned: false }, async () => {});
	assert.equal(restarted.filter(message).projects[0].path, alpha);
	console.log('Project actions passed: Yes/No, cancellation, names, pins and restart persistence.');
})().catch(error => { console.error(error); process.exitCode = 1; });
