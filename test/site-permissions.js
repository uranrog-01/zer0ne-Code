'use strict';
const assert = require('node:assert/strict');
const { installSitePermissions } = require('../app/site-permissions');
const { startupQueue } = require('../app/startup-queue');
(async () => {
	let check, request, url = 'https://example.com/page', response = 0, prompts = 0, resolve;
	const wc = { id: 1, getURL: () => url, reload() {}, session: { setPermissionCheckHandler: f => check = f, setPermissionRequestHandler: f => request = f } };
	const win = { webContents: wc, isDestroyed: () => false };
	const manager = installSitePermissions(win, { showMessageBox: async (_w, options) => { prompts++; assert.equal(options.defaultId, 0); return resolve ? await new Promise(r => resolve(r)) : { response }; } });
	const ask = (permission, details = {}, contents = wc) => new Promise(r => request(contents, permission, r, { requestingUrl: url, ...details }));
	assert.equal(check(wc, 'notifications', url), false);
	assert.equal(await ask('notifications'), false);
	response = 1; assert.equal(await ask('media', { mediaTypes: ['video'] }), true);
	assert.equal(check(wc, 'media', url, { mediaType: 'video' }), true);
	assert.equal(check(wc, 'media', url, { mediaType: 'audio' }), false);
	assert.equal(await ask('unknown'), false);
	assert.equal(await ask('notifications', { requestingUrl: 'https://attacker.example' }), false);
	assert.equal(await ask('notifications', {}, { ...wc, id: 2 }), false);
	assert.equal(prompts, 2);
	let releasePrompt;
	resolve = r => { releasePrompt = r; };
	const pending = ask('geolocation'); manager.revoke(); releasePrompt({ response: 1 });
	assert.equal(await pending, false); assert.equal(check(wc, 'media', url, { mediaType: 'video' }), false);
	resolve = r => { releasePrompt = r; };
	const navigated = ask('notifications'); url = 'https://other.example'; releasePrompt({ response: 1 }); assert.equal(await navigated, false);
	const enqueue = startupQueue(2), started = [], releases = [], cancel = [];
	for (let i = 0; i < 5; i++) cancel.push(enqueue(release => { started.push(i); releases[i] = release; }));
	assert.deepEqual(started, [0, 1]); cancel[3](); releases[0](); assert.deepEqual(started, [0, 1, 2]);
	releases[1](); assert.deepEqual(started, [0, 1, 2, 4]); releases[1](); releases[2](); releases[4]();
	console.log('Site permissions: default deny, camera/microphone isolation, caller/origin binding, revocation/navigation races. Workspace startup: bounded concurrency and cancellation.');
})().catch(e => { console.error(e); process.exitCode = 1; });
