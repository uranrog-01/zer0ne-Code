'use strict';
const assert = require('assert');
const fs = require('fs');
const path = require('path');
const { JSDOM } = require('jsdom');
const source = fs.readFileSync(path.join(__dirname, '../app/desktop-ui.js'), 'utf8');
const start = source.indexOf('\tfunction resizable() {');
const end = source.indexOf('\n\t/**', start);
const dom = new JSDOM('<body><aside id="sidebar" class="hidden"><div class="sidebar-head-tools"></div></aside><aside id="auxiliary" class="hidden"><div class="auxiliary-head-tools"></div></aside></body>', {runScripts:'outside-only'});
const w = dom.window;
const sent = [];
const resizeCallbacks = [];
w.innerWidth = 0;
w.ResizeObserver = class { constructor(callback) { resizeCallbacks.push(callback); } observe() {} };
w.requestAnimationFrame = callback => callback();
w.post = message => sent.push(JSON.parse(JSON.stringify(message)));
for (const [id, variable, fallback] of [['sidebar','--zc-side-w',320],['auxiliary','--zc-aux-w',360]]) {
 const panel = w.document.getElementById(id);
 panel.getBoundingClientRect = () => ({width:panel.classList.contains('hidden') ? 0 : parseFloat(w.document.body.style.getPropertyValue(variable)) || fallback});
}
w.eval('let updatePanelWidths = () => {}, refreshPanelLayout = () => {};\n' + source.slice(start, end) + '\nresizable(); window.restoreWidths = widths => updatePanelWidths(widths);');
w.restoreWidths({sidebar:343, auxiliary:377});
assert.equal(w.document.body.style.getPropertyValue('--zc-side-w'), '', 'a zero-width staging view never collapses a panel');
w.innerWidth = 1280;
w.dispatchEvent(new w.MessageEvent('message', {data:{type:'zcDesktopActivated'}}));
assert.equal(w.document.body.style.getPropertyValue('--zc-side-w'), '343px', 'activation restores saved Projects width');
assert.equal(w.document.body.style.getPropertyValue('--zc-aux-w'), '377px', 'activation restores saved Work Details width');
w.innerWidth = 0;
resizeCallbacks.forEach(callback => callback());
assert.equal(w.document.body.style.getPropertyValue('--zc-side-w'), '343px', 'retiring a page preserves its last usable width');
w.innerWidth = 1280;
for (const id of ['sidebar','auxiliary']) w.document.getElementById(id).classList.remove('hidden');
const grip = w.document.querySelector('#sidebar .zc-resize');
for (let index = 0; index < 3; index++) grip.dispatchEvent(new w.KeyboardEvent('keydown', {key:'ArrowRight',bubbles:true}));
assert.equal(sent.length, 1, 'rapid resizes coalesce while a preference write is pending');
w.restoreWidths(sent[0].prefs.widths);
assert.equal(sent.length, 2, 'the acknowledgment saves the latest requested size');
assert.equal(sent[1].prefs.widths.sidebar, 373);
w.restoreWidths(sent[1].prefs.widths);
assert.equal(w.document.body.style.getPropertyValue('--zc-side-w'), '373px', 'a delayed acknowledgment cannot undo a newer resize');
grip.setPointerCapture = () => {}; grip.hasPointerCapture = () => false;
const pointer = (type, clientX) => grip.dispatchEvent(new w.MouseEvent(type, { clientX, button: 0, bubbles: true, cancelable: true }));
const count = sent.length;
pointer('pointerdown', 373); pointer('pointermove', 375); assert.equal(w.document.body.style.getPropertyValue('--zc-side-w'), '373px'); pointer('pointerup', 375); assert.equal(sent.length, count);
pointer('pointerdown', 373); pointer('pointermove', 423); assert.equal(w.document.body.style.getPropertyValue('--zc-side-w'), '423px');
w.document.dispatchEvent(new w.KeyboardEvent('keydown', { key: 'Escape', bubbles: true, cancelable: true }));
assert.equal(w.document.body.style.getPropertyValue('--zc-side-w'), '373px'); assert(!w.document.body.classList.contains('zc-resizing'));
w.restoreWidths(sent.at(-1).prefs.widths);
pointer('pointerdown', 373); pointer('pointermove', 413); pointer('pointercancel', 413); assert.equal(w.document.body.style.getPropertyValue('--zc-side-w'), '373px');
dom.window.close();
console.log('Panel resize passed: zero-width staging views, activation, retirement and delayed preferences.');
