'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const { contains, deletionTarget, deleteFolder } = require('../app/project-folders');
const { desktopProjects, desktopOpenIn } = require('../host/host');

(async () => {
	const temporary = fs.mkdtempSync(path.join(os.tmpdir(), 'zc-folder-actions-'));
	try {
		const folder = path.join(temporary, 'project & literal'); fs.mkdirSync(folder);
		fs.writeFileSync(path.join(folder, 'keep.txt'), 'saved work');
		assert(contains(folder, path.join(folder, 'child')));
		assert(!contains(folder, folder + '-other'));
		assert.throws(() => deletionTarget('relative'), /absolute/);
		assert.throws(() => deletionTarget(path.parse(folder).root), /cannot be deleted/);
		assert.throws(() => deletionTarget(temporary, [folder]), /cannot be deleted/);
		assert.throws(() => deletionTarget(folder, [temporary]), /cannot be deleted/);
		const calls = [];
		const options = { protectedPaths: [], check: () => calls.push('check'), confirm: async () => false, release: async () => calls.push('release'), trash: async p => calls.push(p) };
		assert.equal(await deleteFolder(folder, options), false);
		assert.deepEqual(calls, ['check'], 'No never stops engines or recycles files');
		calls.length = 0;
		await assert.rejects(deleteFolder(folder, { ...options, check: () => { throw new Error('Running'); }, confirm: async () => { throw new Error('must not prompt'); } }), /Running/);
		assert.equal(await deleteFolder(folder, { ...options, confirm: async () => true }), true);
		assert.deepEqual(calls, ['check', 'check', 'release', 'check', fs.realpathSync.native(folder)]);
		await assert.rejects(deleteFolder(folder, { ...options, confirm: async () => true, trash: async () => { throw new Error('Recycle Bin unavailable'); } }), /Recycle Bin unavailable/);
		let confirmed = false;
		await assert.rejects(deleteFolder(folder, { ...options, confirm: async () => { confirmed = true; return true; }, check: () => { if (confirmed) throw new Error('Session started during confirmation'); } }), /Session started/);
		const linked = path.join(temporary, 'linked');
		fs.symlinkSync(folder, linked, process.platform === 'win32' ? 'junction' : 'dir');
		assert.throws(() => deletionTarget(linked), /linked folder/);

		const values = { 'aiChat.projects': [folder] };
		const state = { get: (key, fallback) => values[key] ?? fallback, update: async (key, value) => { values[key] = value; }, flush() {} };
		let recycle = false; const requests = [];
		const key = p => p.toLowerCase();
		const projects = desktopProjects({ globalState: state }, key, async (op, args) => { requests.push({ op, args }); return recycle; });
		projects.filter({ type: 'projects', projects: [{ id: key(folder), path: folder, current: true, chats: [] }] });
		await assert.rejects(projects.handle({ type: 'projectDelete', path: temporary }, async () => {}), /project list/);
		assert.equal(requests.length, 0, 'unlisted paths never reach the shell');
		await assert.rejects(projects.handle({ type: 'projectShowFiles', path: temporary }, async () => {}), /project list/);
		assert.equal(requests.length, 0, 'Show Files refuses unlisted paths');
		await projects.handle({ type: 'projectShowFiles', path: folder }, async () => {});
		assert.deepEqual(requests, [{ op: 'openFolder', args: { path: folder, newWindow: false, handoff: { kind: 'files' } } }]);
		requests.length = 0;
		await projects.handle({ type: 'projectDelete', path: folder }, async () => {});
		assert.deepEqual(values['aiChat.projects'], [folder], 'cancel preserves project registration');
		recycle = true;
		await projects.handle({ type: 'projectDelete', path: folder }, async () => {});
		assert.deepEqual(values['aiChat.projects'], []);
		assert.deepEqual(values['zer0neDesktop.hiddenProjects'], [key(folder)]);
		assert.equal(requests.at(-1).op, 'projectFolderDeleted');
		assert.equal(fs.readFileSync(path.join(folder, 'keep.txt'), 'utf8'), 'saved work', 'tests never recycle user files');

		const vm = require('node:vm');
		let answer = 0; const nativeCalls = [];
		const context = { module: { exports: {} }, __dirname: path.resolve(__dirname, '../app'), Buffer, process, setTimeout, clearTimeout, require: name => {
			if (name === 'electron') return { dialog: { showMessageBox: async (_win, options) => { nativeCalls.push(options); return { response: answer }; } }, shell: { trashItem: async value => nativeCalls.push(value) } };
			if (name === './paths') return { appRoot: () => path.resolve(__dirname, '..'), configDir: () => path.join(temporary, 'data') };
			return name.startsWith('./') ? require(path.join(__dirname, '..', 'app', name)) : require(name);
		} };
		vm.runInNewContext(fs.readFileSync(path.join(__dirname, '../app/engines.js'), 'utf8'), context);
		const window = Object.create(context.module.exports.EngineWindow.prototype);
		fs.mkdirSync(path.join(folder, 'child'));
		const engine = { folder, key: folder.toLowerCase(), busy: false, remote: false, terminal: false, router: false };
		const peer = { folder: path.join(folder, 'child'), key: path.join(folder, 'child').toLowerCase(), exited: false };
		window.win = {}; window.engines = new Map([[engine.key, engine]]); window.pending = null;
		const peerWindow = { engines: new Map([[peer.key, peer]]), isShown: () => false, retire: r => { r.exited = true; peerWindow.engines.clear(); } };
		window.shell = { windows: new Set([window, peerWindow]) };
		assert.equal(await window.deleteProjectFolder(engine, folder), false);
		assert.equal(peer.exited, false, 'No keeps other project engines alive');
		assert.deepEqual(Array.from(nativeCalls[0].buttons), ['No', 'Yes']);
		assert.equal(nativeCalls[0].defaultId, 0);
		engine.busy = true;
		await assert.rejects(window.deleteProjectFolder(engine, folder), /Stop the running sessions/);
		engine.busy = false; answer = 1;
		assert.equal(await window.deleteProjectFolder(engine, folder), true);
		assert.equal(peer.exited, true, 'idle nested engines release their directory before recycling');
		assert.equal(nativeCalls.at(-1), fs.realpathSync.native(folder));
		assert.equal(window.shell.deletingProject, false);
		assert.equal(engine.deletedFolder, folder);
		window.shell.state = { folder, recent: [folder, temporary] };
		window.shell.saveState = () => {};
		const replies = [];
		window.send = (_engine, message) => replies.push(message);
		window.folder = folder; window.active = engine;
		window.showStartPage = () => { window.active = null; };
		window.retire = record => window.engines.delete(record.key);
		window.onRequest(engine, { id: 10, op: 'projectFolderDeleted', path: temporary });
		assert.equal(replies.at(-1).value, false, 'an unconfirmed folder cannot close project engines');
		assert.equal(window.engines.size, 1);
		window.onRequest(engine, { id: 11, op: 'projectFolderDeleted', path: folder });
		assert.equal(replies.at(-1).value, true);
		assert.equal(window.folder, null, 'the deleted current folder returns to the start page');
		assert.equal(window.engines.size, 0);
		assert.deepEqual(window.shell.state.recent, [temporary]);
		assert.equal(window.shell.state.folder, null);

		const posted = [];
		desktopOpenIn(async () => { throw new Error('Launch failed'); }).handle({ type: 'zcOpenIn', target: 'vscode' }, value => posted.push(value));
		await new Promise(resolve => setImmediate(resolve));
		assert.equal(posted[0].message, 'Launch failed');
		const { folderToolArgs } = require('../app/ops');
		assert.deepEqual(folderToolArgs('vscode', 'Code.exe', folder), ['--new-window', folder]);
		assert.deepEqual(folderToolArgs('terminal', 'wt.exe', folder), ['-d', folder]);
		assert.deepEqual(folderToolArgs('terminal', 'powershell.exe', folder), ['-NoProfile', '-NoLogo', '-NoExit']);
		console.log('project-folder-actions tests passed');
	} finally {
		const resolved = path.resolve(temporary);
		assert(contains(os.tmpdir(), resolved) && path.basename(resolved).startsWith('zc-folder-actions-'));
		fs.rmSync(resolved, { recursive: true, force: true });
	}
})().catch(error => { console.error(error); process.exitCode = 1; });
